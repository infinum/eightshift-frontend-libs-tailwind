import { mkdir, readdir, writeFile } from 'node:fs/promises';
import { dirname, relative, resolve, sep } from 'node:path';

/**
 * Generate Bun-compatible context modules from caller-supplied definitions.
 *
 * `root` is the base for definition directories; `output` is the generated
 * module path. Each definition has `name`, `directory`, `pattern` (RegExp),
 * and optional `mode` (`sync`, the default, or `lazy`). Lazy contexts return
 * promises and do not import their modules until called. CSS is supported only
 * in synchronous contexts, where it is imported for side effects and resolves
 * to an empty object. JSON contexts return parsed values; other synchronous
 * imports return module namespaces. Regenerate after changing source files.
 * Symlinks are skipped. Missing directories are treated as empty contexts.
 * Names cannot shadow the generated helpers or Map, Promise and Error.
 */
export async function generateDiscovery({ root, output, definitions }) {
	if (typeof root !== 'string' || typeof output !== 'string' || !Array.isArray(definitions)) {
		throw new TypeError('Expected root, output, and definitions');
	}

	const baseRoot = resolve(root);
	const outputFile = resolve(baseRoot, output);
	const outputDirectory = dirname(outputFile);
	const names = new Set();
	const imports = [];
	const contexts = [];
	let counter = 0;

	for (const definition of definitions) {
		const { name, directory, pattern, mode = 'sync' } = definition;

		if (
			typeof name !== 'string' ||
			!/^[$A-Z_a-z][$\w]*$/.test(name) ||
			!isValidExportName(name) ||
			['createContext', 'Map', 'Promise', 'Error'].includes(name) ||
			/^module\d+$/.test(name) ||
			names.has(name) ||
			typeof directory !== 'string' ||
			!(pattern instanceof RegExp) ||
			!['sync', 'lazy'].includes(mode)
		) {
			throw new TypeError('Invalid or duplicate discovery definition');
		}

		names.add(name);
		const base = resolve(baseRoot, directory);
		const entries = [];

		for (const file of await filesIn(base)) {
			const key = `./${file}`;

			pattern.lastIndex = 0;

			if (!pattern.test(key)) {
				continue;
			}

			let specifier = relative(outputDirectory, resolve(base, file)).split(sep).join('/');

			if (!specifier.startsWith('./') && !specifier.startsWith('../')) {
				specifier = `./${specifier}`;
			}

			const quoted = JSON.stringify(specifier);

			if (mode === 'lazy') {
				if (file.endsWith('.css')) {
					throw new TypeError(`Lazy CSS context is not supported: ${name}`);
				}

				entries.push(`[${JSON.stringify(key)}, () => import(${quoted})]`);
			} else if (file.endsWith('.css')) {
				imports.push(`import ${quoted};`);
				entries.push(`[${JSON.stringify(key)}, {}]`);
			} else {
				const variable = `module${counter++}`;

				imports.push(file.endsWith('.json') ? `import ${variable} from ${quoted};` : `import * as ${variable} from ${quoted};`);
				entries.push(`[${JSON.stringify(key)}, ${variable}]`);
			}
		}

		contexts.push(`export const ${name} = createContext([${entries.join(',\n')}], ${mode === 'lazy'});`);
	}

	const source = `// Generated by Bun discovery; do not edit.\n${imports.join('\n')}\n\nfunction createContext(entries, lazy) {\n\tconst modules = new Map(entries);\n\tconst context = (key) => {\n\t\tif (!modules.has(key)) {\n\t\t\tconst error = new Error(\`Cannot find module '\${key}'\`);\n\t\t\terror.code = 'MODULE_NOT_FOUND';\n\t\t\tif (lazy) return Promise.reject(error);\n\t\t\tthrow error;\n\t\t}\n\t\treturn lazy ? modules.get(key)() : modules.get(key);\n\t};\n\tcontext.keys = () => [...modules.keys()];\n\treturn context;\n}\n\n${contexts.join('\n\n')}\n`;

	await mkdir(outputDirectory, { recursive: true });
	await writeFile(outputFile, source);

	return { output: outputFile, contexts: definitions.length };
}

function isValidExportName(name) {
	try {
		new Function(`"use strict"; let ${name};`);

		return true;
	} catch {
		return false;
	}
}

async function filesIn(directory, prefix = '') {
	let entries;

	try {
		entries = await readdir(directory, { withFileTypes: true });
	} catch (error) {
		if (error.code === 'ENOENT') {
			return [];
		}

		throw error;
	}

	const files = [];

	for (const entry of entries.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))) {
		const name = prefix ? `${prefix}/${entry.name}` : entry.name;

		if (entry.isDirectory()) {
			files.push(...(await filesIn(resolve(directory, entry.name), name)));
		} else if (entry.isFile()) {
			files.push(name);
		}
	}

	return files;
}
